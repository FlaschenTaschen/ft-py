    CHAR_WIDTH = 5
    CHAR_HEIGHT = 5

    @classmethod
    def render_char(cls, char, scale=1):
        """
        Render a single character to a 2D pixel array.

        Args:
            char: Character to render
            scale: Scaling factor (1=5x5, 2=10x10, etc.)

        Returns:
            2D list of pixels (1=on, 0=off)
        """
        if char not in cls.FONT_DATA:
            char = ' '

        rows = cls.FONT_DATA[char]
        width = cls.CHAR_WIDTH * scale
        height = cls.CHAR_HEIGHT * scale

        # Create scaled bitmap
        bitmap = [[0] * width for _ in range(height)]

        for row_idx, row_data in enumerate(rows):
            for col_idx in range(cls.CHAR_WIDTH):
                # Get bit value for this pixel
                bit_set = (row_data >> (cls.CHAR_WIDTH - 1 - col_idx)) & 1

                # Scale the pixel
                for dy in range(scale):
                    for dx in range(scale):
                        bitmap[row_idx * scale + dy][col_idx * scale + dx] = bit_set

        return bitmap

    @classmethod
    def get_text_width(cls, text, scale=1):
        """Get total width of rendered text."""
        return len(text) * cls.CHAR_WIDTH * scale

    @classmethod
    def get_text_height(cls, scale=1):
        """Get height of rendered text."""
        return cls.CHAR_HEIGHT * scale
